const PATTERNS: [RegExp, (...m: string[]) => string][] = [
  [/^Enter Zone (\d+)$/, n => `进入干涉区 ${n}`],
  [/^Exit Zone (\d+)$/, n => `离开干涉区 ${n}`],
  [/^Finish Segment (\d+)$/, n => `完成（驶出）工作位 ${n}`],
  [/^Segment (\d+)$/, n => `驶入工作位 ${n}`],
  [/^(LALW[A-Z]\d+)$/, id => `焊点编号 ${id}`],
  [/^CALL (\w+)\((.*)\)$/, (p, a) => `调用示例：CALL ${p}(${a})`],
  [/^\*+$/, s => s],
  [/^(END_TASK|ENTER_ZONE|EXIT_ZONE|FinishSeg|IO_RESET|SEGMENT)$/, s => `程序名：${s}`],
]

const MESSAGE: [RegExp, (...m: string[]) => string][] = [
  [/^ROBOT IN ZONE (\d+)$/, n => `机器人已进入干涉区 ${n}`],
  [/^ROBOT CLEAR OF ZONE (\d+)$/, n => `机器人已离开干涉区 ${n}`],
  [/^ROBOT FINISH SEGMENT (\d+)$/, n => `机器人已完成工作位 ${n}`],
  [/^ROBOT IN SEGMENT (\d+)$/, n => `机器人已进入工作位 ${n}`],
  [/^Collision Request$/, () => '干涉区请求'],
  [/^Collision Release$/, () => '干涉区释放'],
  [/^Number invalid$/, () => '编号无效'],
  [/^min 1 to max 16$/, () => '范围 1 ~ 16'],
  [/^Finish Seg Num invalid$/, () => '完成工作位编号无效'],
  [/^Run Seg Num invalid$/, () => '运行工作位编号无效'],
  [/^Invalid gun or posn num$/, () => '焊枪号或位置号无效'],
  [/^ABORTING$/, () => '程序中止'],
]

const HAS_CJK = /[一-鿿]/

export function translateComment(raw: string): string | undefined {
  const s = raw.trim()
  if (!s || HAS_CJK.test(s))
    return undefined
  if (s in EXACT)
    return EXACT[s] === s ? undefined : EXACT[s]
  for (const [re, fn] of PATTERNS) {
    const m = s.match(re)
    if (m) {
      const r = fn(...m.slice(1))
      return r === s ? undefined : r
    }
  }
  return undefined
}

export function translateMessage(raw: string): string {
  const s = raw.trim()
  for (const [re, fn] of MESSAGE) {
    const m = s.match(re)
    if (m)
      return fn(...m.slice(1))
  }
  return s
}
